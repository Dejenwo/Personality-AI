def _original_items(prefix: str, trait: str, statements: list[tuple[str, Keyed, str]]) -> list[dict[str, Any]]:
    items = []
    for index, (text, keyed, facet) in enumerate(statements, start=1):
        items.append(_item(f"{prefix}_{index:02d}", text, trait, keyed, facet))
    return items


