from typing import Any, Literal

Keyed = Literal["+", "-"]


def _item(
    item_id: str,
    text: str,
    trait: str,
    keyed: Keyed,
    facet: str | None = None,
) -> dict[str, Any]:
    return {
        "id": item_id,
        "text": text,
        "trait": trait,
        "keyed": keyed,
        "facet": facet or trait,
        "min_value": 1,
        "max_value": 5,
    }


